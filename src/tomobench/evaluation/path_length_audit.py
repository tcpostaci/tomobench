"""Audit whether the stored ray-path length is privileged target-model information."""

from __future__ import annotations

import csv
import hashlib
import json
import platform
import sys
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from tomobench.simulation.travel_times import PSEUDO_BENDING_3D_METHOD
from tomobench.utils.paths import get_repo_root


PATH_LENGTH_AUDIT_VERSION = "privileged_path_length_audit_v1"
DEFAULT_PATH_LENGTH_MANIFEST_PATH = Path(
    "outputs/datasets/ml_supervised/paper_pseudo_bending_observation_pairs_v1/manifest.json"
)
DEFAULT_PATH_LENGTH_OUTPUT_DIR = Path(
    "outputs/generated/submission_readiness/privileged_path_length_audit_v1"
)


class PathLengthAuditOutputs:
    """Paths written by the path-length provenance audit."""

    def __init__(
        self,
        *,
        output_dir: Path,
        case_summary_csv: Path,
        sample_diagnostics_csv: Path,
        audit_summary_md: Path,
        audit_metadata_json: Path,
    ) -> None:
        self.output_dir = output_dir
        self.case_summary_csv = case_summary_csv
        self.sample_diagnostics_csv = sample_diagnostics_csv
        self.audit_summary_md = audit_summary_md
        self.audit_metadata_json = audit_metadata_json


def run_path_length_audit(
    *,
    manifest_path: Path = DEFAULT_PATH_LENGTH_MANIFEST_PATH,
    output_dir: Path = DEFAULT_PATH_LENGTH_OUTPUT_DIR,
) -> PathLengthAuditOutputs:
    """Compare stored path lengths with Euclidean source-receiver distances.

    For the pseudo-bending corpus, the stored value is populated by the
    ray-tracer result.  A nonzero difference from Euclidean distance is direct
    numerical evidence that the feature contains bent-path information; the
    implementation provenance recorded in the Markdown artifact establishes
    that the path was traced through the target velocity grid.
    """
    repo_root = get_repo_root()
    resolved_manifest_path = _resolve_path(Path(manifest_path), repo_root)
    resolved_output_dir = _resolve_path(Path(output_dir), repo_root)
    _require_file(resolved_manifest_path, "corpus manifest")
    manifest = _read_json(resolved_manifest_path)
    items = manifest.get("items")
    if not isinstance(items, list):
        raise ValueError("Corpus manifest must contain an items list.")

    case_rows: list[dict[str, Any]] = []
    sample_rows: list[dict[str, Any]] = []
    method_counts: defaultdict[str, int] = defaultdict(int)
    for item in items:
        if not isinstance(item, dict):
            raise ValueError("Corpus manifest items must be objects.")
        case_id = str(item.get("case_id", ""))
        dataset_path = _resolve_manifest_path(
            Path(str(item.get("input_dataset_csv_path", ""))),
            resolved_manifest_path,
            repo_root,
        )
        _require_file(dataset_path, f"dataset for {case_id}")
        diagnostics = _read_dataset_rows(dataset_path, case_id, item)
        case_rows.append(diagnostics["case_row"])
        sample_rows.extend(diagnostics["sample_rows"])
        method_counts.update(diagnostics["method_counts"])

    nonzero_rows = [row for row in sample_rows if row["absolute_difference_km"] > 1.0e-12]
    maximum_difference = max(
        (float(row["absolute_difference_km"]) for row in sample_rows),
        default=0.0,
    )
    resolved_output_dir.mkdir(parents=True, exist_ok=True)
    case_summary_csv = resolved_output_dir / "path_length_case_summary.csv"
    sample_diagnostics_csv = resolved_output_dir / "path_length_sample_diagnostics.csv"
    audit_summary_md = resolved_output_dir / "audit_summary.md"
    audit_metadata_json = resolved_output_dir / "audit_metadata.json"
    _write_csv(case_summary_csv, case_rows)
    _write_csv(sample_diagnostics_csv, sample_rows)

    summary_payload = {
        "artifact_type": PATH_LENGTH_AUDIT_VERSION,
        "generated_at_utc": datetime.now(UTC).isoformat(),
        "manifest_path": _relative_or_absolute(resolved_manifest_path, repo_root),
        "case_count": len(case_rows),
        "sample_count": len(sample_rows),
        "nonzero_bent_path_difference_count": len(nonzero_rows),
        "nonzero_bent_path_difference_fraction": (
            len(nonzero_rows) / len(sample_rows) if sample_rows else 0.0
        ),
        "maximum_absolute_difference_km": maximum_difference,
        "simulation_method_counts": dict(sorted(method_counts.items())),
        "conclusion": (
            "The path_length_km feature is privileged target-model ray-path information for "
            "the pseudo-bending corpus: it is generated by tracing through each target velocity "
            "grid and is not generally available before the unknown model is recovered."
            if any(row["simulation_method"] == PSEUDO_BENDING_3D_METHOD for row in sample_rows)
            else "The supplied corpus did not contain pseudo-bending rows; provenance requires review."
        ),
        "fair_alternative": {
            "feature_id": "euclidean_source_receiver_distance_km",
            "definition": "Straight-line Euclidean distance calculated from source and receiver coordinates.",
            "implementation": "Grouped ablation variants replace path_length_km with this feature without using the target velocity grid.",
        },
        "implementation_evidence": [
            {
                "source_file": "code/src/tomobench/simulation/travel_times.py",
                "symbol": "PseudoBending3DTravelTimeSimulator.simulate_with_ray_paths",
                "evidence": "The pseudo-bending observation stores path_length_km from the ray-tracer result returned for the target velocity grid.",
            },
            {
                "source_file": "code/src/tomobench/simulation/ray_tracing.py",
                "symbol": "trace_pseudo_bending_ray",
                "evidence": "The ray tracer constructs its interpolator from the supplied Cartesian velocity grid and returns the optimized polyline length.",
            },
        ],
        "interpretation_cautions": [
            "The Euclidean alternative removes bent-path length information but does not model reference-model ray tracing.",
            "The audit is a provenance and numerical diagnostic; it does not claim that the full feature vector is otherwise free of synthetic-data priors.",
        ],
    }
    _write_json(summary_payload, resolved_output_dir / "path_length_audit_summary.json")
    _write_json(
        {
            "artifact_type": f"{PATH_LENGTH_AUDIT_VERSION}_metadata",
            "command": "uv run tomobench audit-path-length-feature",
            "python_version": sys.version,
            "platform": platform.platform(),
            "manifest_sha256": _file_sha256(resolved_manifest_path),
            "euclidean_tolerance_km": 1.0e-12,
        },
        audit_metadata_json,
    )
    _write_markdown_summary(
        audit_summary_md,
        summary_payload,
        case_summary_csv,
        sample_diagnostics_csv,
        repo_root,
    )
    return PathLengthAuditOutputs(
        output_dir=resolved_output_dir,
        case_summary_csv=case_summary_csv,
        sample_diagnostics_csv=sample_diagnostics_csv,
        audit_summary_md=audit_summary_md,
        audit_metadata_json=audit_metadata_json,
    )


def _read_dataset_rows(
    dataset_path: Path,
    case_id: str,
    manifest_item: dict[str, Any],
) -> dict[str, Any]:
    sample_rows: list[dict[str, Any]] = []
    method_counts: defaultdict[str, int] = defaultdict(int)
    with dataset_path.open("r", newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise ValueError(f"Dataset is empty for {case_id}: {dataset_path}")
    for row in rows:
        source = tuple(float(row[f"source_{axis}_km"]) for axis in ("x", "y", "z"))
        receiver = tuple(float(row[f"receiver_{axis}_km"]) for axis in ("x", "y", "z"))
        euclidean = sum((left - right) ** 2 for left, right in zip(source, receiver, strict=True)) ** 0.5
        stored = float(row["path_length_km"])
        method = str(row.get("simulation_method", ""))
        method_counts[method] += 1
        sample_rows.append(
            {
                "case_id": case_id,
                "family": str(manifest_item.get("scenario") or manifest_item.get("family") or ""),
                "geometry_profile_id": str(manifest_item.get("geometry_profile_id") or ""),
                "observation_id": str(row.get("observation_id", "")),
                "simulation_method": method,
                "stored_path_length_km": stored,
                "euclidean_distance_km": euclidean,
                "difference_km": stored - euclidean,
                "absolute_difference_km": abs(stored - euclidean),
                "relative_difference": abs(stored - euclidean) / euclidean
                if euclidean > 0.0
                else None,
            }
        )
    absolute_differences = [float(row["absolute_difference_km"]) for row in sample_rows]
    case_row = {
        "case_id": case_id,
        "family": str(manifest_item.get("scenario") or manifest_item.get("family") or ""),
        "geometry_profile_id": str(manifest_item.get("geometry_profile_id") or ""),
        "row_count": len(sample_rows),
        "simulation_methods": ";".join(sorted(method_counts)),
        "nonzero_difference_count": sum(value > 1.0e-12 for value in absolute_differences),
        "nonzero_difference_fraction": sum(value > 1.0e-12 for value in absolute_differences)
        / len(absolute_differences),
        "mean_absolute_difference_km": sum(absolute_differences) / len(absolute_differences),
        "maximum_absolute_difference_km": max(absolute_differences),
    }
    return {
        "case_row": case_row,
        "sample_rows": sample_rows,
        "method_counts": method_counts,
    }


def _resolve_manifest_path(path: Path, manifest_path: Path, repo_root: Path) -> Path:
    if path.is_absolute():
        return path
    repo_candidate = repo_root / path
    if repo_candidate.is_file():
        return repo_candidate
    return manifest_path.parent / path


def _write_markdown_summary(
    path: Path,
    payload: dict[str, Any],
    case_summary_csv: Path,
    sample_diagnostics_csv: Path,
    repo_root: Path,
) -> None:
    lines = [
        "# Path-Length Feature Provenance Audit",
        "",
        f"Generated: `{payload['generated_at_utc']}`",
        "",
        "## Finding",
        "",
        payload["conclusion"],
        "",
        f"- Cases: `{payload['case_count']}`",
        f"- Observations: `{payload['sample_count']}`",
        f"- Observations with non-Euclidean stored path length: `{payload['nonzero_bent_path_difference_count']}` ({float(payload['nonzero_bent_path_difference_fraction']):.3f})",
        f"- Maximum absolute difference: `{float(payload['maximum_absolute_difference_km']):.6f}` km",
        "",
        "## Fair Alternative",
        "",
        "Use `euclidean_source_receiver_distance_km`, calculated from source and receiver coordinates, as the realistic geometry-only path-length alternative. The original path-length feature remains available as a clearly labeled privileged diagnostic.",
        "",
        "## Implementation Evidence",
        "",
    ]
    lines.extend(
        f"- `{item['source_file']}` / `{item['symbol']}`: {item['evidence']}"
        for item in payload["implementation_evidence"]
    )
    lines.extend(
        [
            "",
            "## Outputs",
            "",
            f"- Case summary: `{_relative_or_absolute(case_summary_csv, repo_root)}`",
            f"- Sample diagnostics: `{_relative_or_absolute(sample_diagnostics_csv, repo_root)}`",
            "",
        ]
    )
    path.write_text("\n".join(lines), encoding="utf-8")


def _write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]) if rows else ["case_id"])
        writer.writeheader()
        writer.writerows(rows)


def _write_json(payload: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _read_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"Expected a JSON object: {path}")
    return payload


def _resolve_path(path: Path, repo_root: Path) -> Path:
    return path if path.is_absolute() else repo_root / path


def _relative_or_absolute(path: Path, repo_root: Path) -> str:
    resolved = path.resolve()
    try:
        return resolved.relative_to(repo_root.resolve()).as_posix()
    except ValueError:
        return resolved.as_posix()


def _require_file(path: Path, label: str) -> None:
    if not path.is_file():
        raise FileNotFoundError(f"{label} does not exist: {path}")


def _file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


__all__ = ["PathLengthAuditOutputs", "run_path_length_audit"]
